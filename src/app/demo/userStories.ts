export type EpicKey = 'E1' | 'E2' | 'E3' | 'E4' | 'E5' | 'E6' | 'E7' | 'E8' | 'EK';
export type StoryRole = 'Nhãn hàng' | 'KOL' | 'MCN' | 'Khách' | 'Hệ thống';
export type ReleaseKey = 'R0' | 'R1' | 'R2' | 'R3' | 'R4' | 'R5' | 'R6';

export interface Epic {
  key: EpicKey;
  name: string;
}

export interface StoryError {
  code: string;
  when: string;
  message: string;
}

export interface UserStory {
  id: string;
  epic: EpicKey;
  roles: StoryRole[];
  title: string;
  /** "Là …, tôi muốn … để …". */
  story: string;
  /** Route + screen / block / button as named in the prototype. */
  screens: string[];
  /** Service functions of the prototype. */
  api: string[];
  /** State transitions, or UI states (loading / empty / error). */
  states?: string;
  rules: string[];
  errors?: StoryError[];
  notes?: string[];
  /** Spec section(s) and prototype files. */
  source: string;
  /** "Cần BA xác nhận": spec and prototype disagree, or neither settles it. */
  confirm?: string;
}

export interface Release {
  key: ReleaseKey;
  name: string;
  goal: string;
  stories: UserStory[];
}

